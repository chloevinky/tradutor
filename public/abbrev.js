// Laughter and other pattern-based forms that can't be plain dictionary keys.
window.abbrevLookup = function (word) {
  const w = String(word || '').toLowerCase();
  if (!w) return null;
  if (window.ABBREV[w]) return window.ABBREV[w];
  if (/^k{2,}$/.test(w)) return { to: '(risada)', gloss: 'hahaha — Brazilian keyboard laughter' };
  if (/^(?:ha|he|hu|as|ua|sh){3,}$/.test(w)) return { to: '(risada)', gloss: 'hahaha — laughter' };
  if (/^r(?:s)+r?s*$/.test(w) && w.length > 1) return { to: 'risos', gloss: 'lol (soft laughter)' };
  return null;
};
